/**
 * StepCounter — TypeScript interface for our custom Capacitor plugin.
 *
 * Capacitor lets us define a single JS API that's implemented separately on
 * each platform:
 *   - iOS native:     Swift code talks to HealthKit, registered as "StepCounter".
 *   - Android native: Kotlin code talks to Health Connect, same plugin name.
 *   - Web fallback:   `./web.ts` returns zeros (browsers can't read steps).
 *
 * `registerPlugin` is Capacitor's way of saying "here's the contract, pick
 * the right implementation based on what platform we're running on." That's
 * why this file looks so small — the heavy lifting lives in the native
 * iOS/Android folders generated by `npx cap add ios|android`.
 */
import { registerPlugin } from '@capacitor/core';

/** Shape both native sides MUST implement, and the web shim mimics. */
export interface StepCounterPlugin {
  /** Show the OS permission sheet (HealthKit / Health Connect). */
  requestPermissions(): Promise<{ granted: boolean }>;
  /** Total step count for the user's current local day. */
  getStepsToday(): Promise<{ steps: number }>;
  /** Step count summed over an inclusive ISO datetime range. */
  getStepsForDateRange(options: {
    startDate: string;
    endDate: string
  }): Promise<{ steps: number }>;
  /**
   * Daily step totals for a whole calendar month in ONE bridge call.
   * `month` is 1-12. Backed by HKStatisticsCollectionQuery on iOS, so a month
   * costs a single HealthKit query instead of ~30.
   *
   * Optional: older installed native binaries don't implement it, and
   * HealthService falls back to per-day queries when it's missing.
   */
  getStepsForMonth?(options: {
    year: number;
    month: number;
  }): Promise<{ days: { date: string; steps: number }[] }>;

}

// Lazy-load the web fallback so it's not bundled into native builds.
const StepCounter = registerPlugin<StepCounterPlugin>('StepCounter', {
  web: () => import('./web').then(m => new m.StepCounterWeb()),
});

export default StepCounter;
